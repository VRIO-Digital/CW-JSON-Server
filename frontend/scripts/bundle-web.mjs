/*
 * Builds the Elastic Beanstalk source bundle for the console, and refuses to write a broken one.
 *
 *     npm run build && npm run bundle:web   ->  frontend-eb.zip at the repo root
 *
 * **A zip of `dist/` is not an application, and that is the deploy this file exists to stop.** EB's
 * Node platform looks for `package.json`, `server.js` or `app.js` at the archive root to generate a
 * Procfile from, then waits for something to listen on `PORT`. A static bundle satisfies neither, so
 * the deploy sits until the command times out — `Successful: 0, TimedOut: 1`, which reads as a broken
 * environment rather than as a bundle with no process in it.
 *
 * Three things it therefore guarantees, each of which failed for the backend's bundle first:
 *
 *  1. **The app files are at the archive root**, not inside a folder. Zipping the project directory
 *     puts `frontend/web.js` in the zip and EB finds one directory and no manifest.
 *  2. **No `.env` travels.** These hold no secret — `VITE_*` values are inlined at build time and none
 *     of them can hold one — but they are build-time inputs, and shipping one invites the idea that
 *     editing it on the instance changes the app. The file list is explicit for the same reason
 *     `bundle-eb.js`'s is.
 *  3. **POSIX separators.** `Compress-Archive` writes backslashes and EB then does not recognise the
 *     paths — silently.
 *
 * **The shipped `package.json` is generated, with no dependencies.** The frontend's own names react,
 * antd, d3 and vite: `npm install` on an instance whose whole job is to stream files would install
 * several hundred packages to do it, and any advisory among them would land on a deployed box rather
 * than in the audit gate. Name and version are *read* from the real manifest rather than typed, and
 * `engines` is deliberately absent — EB cannot resolve a range like ">=22", warns, and falls back to
 * the platform default, which is noise on every deploy for a constraint the platform choice already
 * expresses. That reasoning is `backend/package.json`'s, applied here.
 *
 * Zero dependencies, like the rest of this repo's tooling: `node:zlib` has `deflateRawSync` and
 * `crc32`, so the ZIP container below is ~40 lines. It is a second copy of the one in
 * `backend/scripts/bundle-eb.js` **on purpose** — the two packages deploy independently, and a shared
 * helper would mean neither could be zipped without the other on disk.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { crc32, deflateRawSync } from 'node:zlib'

const pkgDir = fileURLToPath(new URL('..', import.meta.url))
const outPath = join(pkgDir, '..', 'frontend-eb.zip')
const distDir = join(pkgDir, 'dist')

const problems = []
const fail = (message) => problems.push(message)

const isFile = (path) => {
  try {
    return statSync(path).isFile()
  } catch {
    return false
  }
}

/** The built site, walked — the filenames are content-hashed, so they cannot be listed by hand. */
const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  )

const manifest = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))

/*
 * What runs on the instance. Written into the bundle rather than committed, so it cannot drift from
 * the two facts it restates: the file that serves, and the command in the Procfile.
 *
 * `start` exists because EB's Node platform runs `npm start` when there is no Procfile. There *is* one
 * here — with a Procfile the platform runs node directly, so a SIGTERM on deploy reaches node rather
 * than an npm wrapper — but a manifest with no start script is a bundle that breaks the moment
 * somebody removes the Procfile for an unrelated reason.
 */
const shipped = {
  name: `${manifest.name}-web`,
  private: true,
  version: manifest.version,
  type: 'module',
  description:
    'Serves the built console on Elastic Beanstalk. Generated by scripts/bundle-web.mjs — no ' +
    'dependencies on purpose: a static file server needs none, and the build already happened.',
  scripts: { start: 'node web.js' },
}

if (!isFile(join(distDir, 'index.html'))) {
  fail(
    'dist/index.html is missing — run "npm run build" before bundling. A bundle with no site in it ' +
      'deploys a server that 503s its own health check.',
  )
}
if (!isFile(join(pkgDir, 'web.js'))) fail('web.js is missing — there would be nothing to run')
if (!isFile(join(pkgDir, 'Procfile'))) fail('Procfile is missing')

if (problems.length === 0) {
  const procfile = readFileSync(join(pkgDir, 'Procfile'), 'utf8')
  /*
   * The Procfile's grammar, checked here because EB checks it after `npm install` and reports it as an
   * rsyslog error naming neither the file nor the line. Every non-empty line must be `name: command`,
   * and a `#` comment is not one — a real trap in a repo that comments everything.
   */
  for (const line of procfile.split(new RegExp('[\r\n]+'))) {
    if (line.trim() === '') continue
    if (line.trimStart().startsWith('#')) fail('Procfile has a comment — EB cannot parse one')
    else if (!/^[A-Za-z0-9_-]+:\s+\S/.test(line)) fail(`Procfile line is not "name: command": ${line}`)
  }
  if (!/^web:\s+node web\.js$/m.test(procfile)) {
    fail('the Procfile does not run web.js — the bundle would start something that is not in it')
  }
  if ('dependencies' in shipped) {
    fail('the shipped manifest names dependencies — the instance would npm install them to serve files')
  }
}

const files =
  problems.length > 0
    ? []
    : [
        ['web.js', readFileSync(join(pkgDir, 'web.js'))],
        ['Procfile', readFileSync(join(pkgDir, 'Procfile'))],
        ['package.json', Buffer.from(`${JSON.stringify(shipped, null, 2)}\n`, 'utf8')],
        ...walk(distDir).map((abs) => [
          `dist/${relative(distDir, abs).split('\\').join('/')}`,
          readFileSync(abs),
        ]),
      ]

/* The three EB looks for at the root, and the rule that nothing resembling an environment file ships. */
for (const required of ['web.js', 'package.json', 'Procfile']) {
  if (files.length > 0 && !files.some(([name]) => name === required)) {
    fail(`${required} must be in the bundle root`)
  }
}
for (const [name] of files) {
  if (/(^|\/)\.env/.test(name)) fail(`${name} looks like an environment file and must not ship`)
  if (name.includes('\\')) fail(`${name} carries a backslash — EB would not recognise the path`)
}

if (problems.length > 0) {
  console.error('\nbundle-web: refusing to write —')
  for (const p of problems) console.error('  · ' + p)
  console.error('')
  process.exit(1)
}

const chunks = []
const central = []
let offset = 0
const u16 = (n) => { const b = Buffer.alloc(2); b.writeUInt16LE(n); return b }
const u32 = (n) => { const b = Buffer.alloc(4); b.writeUInt32LE(n >>> 0); return b }

for (const [name, data] of files) {
  const deflated = deflateRawSync(data)
  const sum = crc32(data)
  const entry = Buffer.from(name, 'utf8')
  const local = Buffer.concat([
    u32(0x04034b50), u16(20), u16(0), u16(8), u16(0), u16(0),
    u32(sum), u32(deflated.length), u32(data.length),
    u16(entry.length), u16(0), entry,
  ])
  chunks.push(local, deflated)
  central.push(Buffer.concat([
    u32(0x02014b50), u16(20), u16(20), u16(0), u16(8), u16(0), u16(0),
    u32(sum), u32(deflated.length), u32(data.length),
    u16(entry.length), u16(0), u16(0), u16(0), u16(0), u32(0), u32(offset), entry,
  ]))
  offset += local.length + deflated.length
}

const dir = Buffer.concat(central)
writeFileSync(
  outPath,
  Buffer.concat([
    ...chunks,
    dir,
    Buffer.concat([
      u32(0x06054b50), u16(0), u16(0),
      u16(files.length), u16(files.length),
      u32(dir.length), u32(offset), u16(0),
    ]),
  ]),
)

console.log(`bundle-web: wrote frontend-eb.zip (${statSync(outPath).size.toLocaleString()} bytes)`)
for (const [name] of files) console.log(`  ${name}`)
console.log('')
console.log('  root layout: web.js · package.json · Procfile · dist/')
console.log('  POSIX separators, no .env, no dependencies to install')
console.log('')
console.log('  The API origin is baked into dist/ by VITE_API_BASE at build time.')
console.log('  Changing it is a rebuild and a re-bundle, never an eb setenv.')
